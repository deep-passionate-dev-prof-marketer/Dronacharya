/**
 * Fast Bidirectional Normalizer
 */
function normalizeForMatch(str: string): string {
  return str
    .toLowerCase()
    .trim()
    .replace(/[.,!?;:।؟¿¡]/g, "")
    .replace(/\s+/g, " ");
}

/**
 * Universal Inverted Multilingual Concept Index
 */
const INVERTED_CORPUS_INDEX = new Map<string, CanonicalConcept>();

for (const concept of MULTILINGUAL_CLASSROOM_CONCEPTS) {
  for (const [, localizedText] of Object.entries(concept.translations)) {
    const key = normalizeForMatch(localizedText);
    INVERTED_CORPUS_INDEX.set(key, concept);
  }
}

/**
 * Look up any input text across all 50 languages and return target translation if matched
 */
export function lookupMultilingualConcept(text: string, targetLang: string): string | null {
  const norm = normalizeForMatch(text);
  const matched = INVERTED_CORPUS_INDEX.get(norm);
  if (matched) {
    const tgt = targetLang.toLowerCase();
    if (matched.translations[tgt]) {
      return matched.translations[tgt];
    }
    // Fallback to English if target not present in concept
    return matched.translations["en"] || null;
  }
  return null;
}
